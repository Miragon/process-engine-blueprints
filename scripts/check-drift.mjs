import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';
import { loadExamples, repoRoot } from './lib/examples.mjs';
import { globMatcher } from './lib/glob.mjs';

const manifestFile = join(repoRoot, 'drift.yml');
const lockFile = join(repoRoot, 'drift.lock.yml');
const lockHeader = '# Generated by `npm run drift:update`, do not edit. Every file listed here is identical (engine names\n# normalized, see drift.yml) in every example of its group. `npm run drift` fails when a copy drifts.\n';

export function engineNormalizer(engines) {
  const spellings = Object.values(engines ?? {}).flat().sort((left, right) => right.length - left.length);
  return (text) => spellings.reduce((normalized, spelling) => normalized.replaceAll(spelling, '{engine}'), text);
}

function scopedMatcher(entries) {
  const scoped = entries.map((entry) => ({ entry, examples: entry.examples, matches: globMatcher(entry.files) }));
  return (example, path) => scoped.find(({ examples, matches }) => (!examples || examples.includes(example)) && matches(path))?.entry;
}

export function snapshot({ examples, filesOf, contentOf, manifest }) {
  const normalize = engineNormalizer(manifest.engines);
  const independent = scopedMatcher(manifest.independent ?? []);
  const files = new Map();
  for (const example of examples) {
    files.set(example, new Map());
    for (const path of filesOf(example)) {
      const normalizedPath = normalize(path);
      if (!independent(example, normalizedPath)) {
        const hash = createHash('sha256').update(normalize(contentOf(example, path))).digest('hex');
        files.get(example).set(normalizedPath, hash);
      }
    }
  }
  return files;
}

export function identicalGroups(files) {
  const examplesByCopy = new Map();
  for (const [example, hashes] of files) {
    for (const [path, hash] of hashes) {
      const key = `${path}\0${hash}`;
      examplesByCopy.set(key, [...(examplesByCopy.get(key) ?? []), example]);
    }
  }
  const pathsByExamples = new Map();
  for (const [key, examples] of examplesByCopy) {
    if (examples.length > 1) {
      const set = examples.sort().join(',');
      pathsByExamples.set(set, [...(pathsByExamples.get(set) ?? []), key.split('\0')[0]]);
    }
  }
  return [...pathsByExamples]
    .map(([set, paths]) => ({ examples: set.split(','), files: paths.sort() }))
    .sort((left, right) => right.examples.length - left.examples.length || left.examples.join().localeCompare(right.examples.join()));
}

function groupsByPath(groups) {
  const byPath = new Map();
  for (const { examples, files } of groups) {
    for (const path of files) byPath.set(path, [...(byPath.get(path) ?? []), examples.join(', ')]);
  }
  return byPath;
}

function copiesIn(groups) {
  return new Set(groups.flatMap(({ examples, files }) => examples.flatMap((example) => files.map((path) => `${example}\0${path}`))));
}

function lockViolations(lock, current) {
  const locked = groupsByPath(lock);
  const now = groupsByPath(current);
  const found = [];
  const drifted = new Map();
  const containedIn = (set, groups) => groups.some((group) => set.split(', ').every((example) => group.split(', ').includes(example)));
  for (const [path, sets] of locked) {
    for (const set of sets.filter((set) => !containedIn(set, now.get(path) ?? []))) {
      const examples = set.split(', ');
      const largestStillAlike = (now.get(path) ?? []).map((group) => group.split(', ').filter((example) => examples.includes(example)))
        .sort((left, right) => right.length - left.length)[0] ?? [];
      const driftedExamples = examples.filter((example) => !largestStillAlike.includes(example));
      found.push(`${path} drifted in ${driftedExamples.join(', ')}: must stay identical to ${largestStillAlike.join(', ') || 'the other copies'}`);
      drifted.set(path, [...(drifted.get(path) ?? []), ...examples]);
    }
  }
  for (const [path, sets] of now) {
    const splitFromDrift = (set) => set.split(', ').every((example) => drifted.get(path)?.includes(example));
    for (const set of sets.filter((set) => !(locked.get(path) ?? []).includes(set) && !splitFromDrift(set))) {
      found.push(`${path} is identical in [${set}] but not locked: run npm run drift:update`);
    }
  }
  return found;
}

function classificationViolations(files, lock, current, manifest) {
  const classified = new Set([...copiesIn(lock), ...copiesIn(current)]);
  const differs = scopedMatcher(manifest.differs ?? []);
  const unclassified = [];
  for (const [example, hashes] of files) {
    for (const path of hashes.keys()) {
      if (!classified.has(`${example}\0${path}`) && !differs(example, path)) unclassified.push(`${example}: ${path}`);
    }
  }
  return unclassified.map((file) => `${file} is neither identical to another example nor listed under differs in drift.yml`);
}

function staleEntryViolations(snapshotFiles, allFiles, lock, manifest) {
  const locked = copiesIn(lock);
  const found = [];
  for (const [section, entries] of [['independent', manifest.independent ?? []], ['differs', manifest.differs ?? []]]) {
    for (const entry of entries) {
      if (!entry.reason?.trim()) found.push(`${section} in drift.yml: ${entry.files.join(', ')} has no reason`);
      for (const pattern of entry.files.filter((pattern) => !pattern.startsWith('!'))) {
        const matches = globMatcher([pattern]);
        const hits = [...allFiles].flatMap(([example, paths]) =>
          (!entry.examples || entry.examples.includes(example)) ? paths.filter(matches).map((path) => `${example}\0${path}`) : []);
        if (hits.length === 0) {
          found.push(`${section} in drift.yml: ${pattern} matches no file, remove it`);
        } else if (section === 'differs' && hits.every((hit) => locked.has(hit) || !snapshotFiles.get(hit.split('\0')[0]).has(hit.split('\0')[1]))) {
          found.push(`differs in drift.yml: every file of ${pattern} is identical now, remove it`);
        }
      }
    }
  }
  return found;
}

const sourcePattern = /^(.*)\/src\/(main|test)\/(?:kotlin|java)\/(.*)\.(?:kt|java)$/;
const testAnnotation = String.raw`@(?:Test|ParameterizedTest|RepeatedTest)\b(?:\([^)]*\))?(?:\s*@\w+(?:\([^)]*\))?)*\s*`;
const testDeclaration = {
  Kotlin: new RegExp(`${testAnnotation}(?:(?:internal|public)\\s+)?fun\\s+(\`[^\`]+\`|\\w+)`, 'g'),
  Java: new RegExp(`${testAnnotation}(?:(?:public|protected)\\s+)?void\\s+(\\w+)`, 'g'),
};

export function comparableTestName(name) {
  return name.replaceAll("'", '').toLowerCase().replace(/[^a-z0-9]+/g, '').replaceAll('null', 'empty');
}

function testNames(language, source) {
  return new Set([...source.matchAll(testDeclaration[language])].map(([declaration, name]) =>
    comparableTestName(declaration.match(/@DisplayName\("([^"]*)"\)/)?.[1] ?? name.replaceAll('`', ''))));
}

export function variantViolations(example, variantFiles, contentOf, languageOnly, normalize = (text) => text) {
  const [kotlin, java] = ['kotlin-gradle', 'java-maven'].map((variant) => variantFiles[variant]);
  if (!kotlin || !java) return [];
  const found = [];
  const sources = (paths) => new Map(paths.map((path) => [path, path.match(sourcePattern)]).filter(([, match]) => match)
    .map(([path, [, module, set, type]]) => [normalize(`${module}/src/${set}/${type}`), path]));
  const kotlinSources = sources(kotlin);
  const javaSources = sources(java);
  const entries = languageOnly.filter((entry) => entry.examples.includes(example.name));
  const allowed = new Set(entries.flatMap((entry) => entry.sources ?? []));
  const allowedTests = new Set(entries.flatMap((entry) => (entry.tests ?? []).map((test) => {
    const [source, name] = test.split('#');
    return `${source}#${comparableTestName(name)}`;
  })));
  for (const [language, own, other] of [['Kotlin', kotlinSources, javaSources], ['Java', javaSources, kotlinSources]]) {
    for (const source of own.keys()) {
      if (!other.has(source) && !allowed.has(source)) found.push(`${example.name}: ${source} exists only in ${language}; add it to the other variant or to languageOnly in drift.yml`);
    }
  }
  for (const source of allowed) {
    if (kotlinSources.has(source) === javaSources.has(source)) found.push(`languageOnly in drift.yml: ${example.name} ${source} is not in exactly one variant, remove it`);
  }
  const usedTests = new Set();
  for (const [source, kotlinPath] of kotlinSources) {
    if (!source.includes('/src/test/') || !javaSources.has(source)) continue;
    const kotlinTests = testNames('Kotlin', contentOf(`kotlin-gradle/${kotlinPath}`));
    const javaTests = testNames('Java', contentOf(`java-maven/${javaSources.get(source)}`));
    for (const [language, own, other] of [['Kotlin', kotlinTests, javaTests], ['Java', javaTests, kotlinTests]]) {
      for (const test of own) {
        const key = `${source}#${test}`;
        if (other.has(test)) continue;
        if (allowedTests.has(key)) usedTests.add(key);
        else found.push(`${example.name}: test ${test} in ${source} exists only in ${language}; name it alike in both variants or add it to languageOnly tests in drift.yml`);
      }
    }
  }
  for (const test of allowedTests) {
    if (!usedTests.has(test)) found.push(`languageOnly in drift.yml: ${example.name} test ${test} is in both variants or in none, remove it`);
  }
  for (const entry of entries.filter((entry) => !entry.reason?.trim())) {
    found.push(`languageOnly in drift.yml: ${[...(entry.sources ?? []), ...(entry.tests ?? [])].join(', ')} has no reason`);
  }
  for (const resource of example.identicalResources) {
    const under = (paths) => paths.filter((path) => path.startsWith(`${resource}/`));
    const kotlinResources = under(kotlin);
    const javaResources = under(java);
    for (const path of new Set([...kotlinResources, ...javaResources])) {
      if (!kotlinResources.includes(path) || !javaResources.includes(path)) {
        found.push(`${example.name}: ${path} is missing in one variant (identicalResources)`);
      } else if (contentOf(`kotlin-gradle/${path}`) !== contentOf(`java-maven/${path}`)) {
        found.push(`${example.name}: ${path} differs between kotlin-gradle and java-maven (identicalResources)`);
      }
    }
  }
  return found;
}

export function checkDrift({ examples, filesOf, contentOf, manifest, lock }) {
  const normalize = engineNormalizer(manifest.engines);
  const files = snapshot({ examples, filesOf, contentOf, manifest });
  const allFiles = new Map(examples.map((example) => [example, filesOf(example).map(normalize)]));
  const current = identicalGroups(files);
  return [
    ...lockViolations(lock, current),
    ...classificationViolations(files, lock, current, manifest),
    ...staleEntryViolations(files, allFiles, lock, manifest),
  ];
}

function trackedFilesByExample() {
  const byExample = new Map();
  for (const path of execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard', 'examples'], { cwd: repoRoot, encoding: 'utf8' }).split('\0').filter(Boolean)) {
    const [, example, ...rest] = path.split('/');
    if (existsSync(join(repoRoot, path))) byExample.set(example, [...(byExample.get(example) ?? []), rest.join('/')]);
  }
  return byExample;
}

export function comparedPath(example, path) {
  const rootVariant = Object.entries(example.variants).find(([, { path: variantPath }]) => variantPath === '.')?.[0];
  return rootVariant && path.startsWith('service/') ? `${rootVariant}/${path}` : path;
}

function variantFilesOf(example, files) {
  const byVariant = {};
  for (const variant of Object.keys(example.variants)) {
    byVariant[variant] = files.filter((path) => path.startsWith(`${variant}/`)).map((path) => path.slice(variant.length + 1));
  }
  return byVariant;
}

function run() {
  const examples = loadExamples();
  const tracked = trackedFilesByExample();
  const manifest = parse(readFileSync(manifestFile, 'utf8')) ?? {};
  const realPaths = new Map(examples.map((example) => [example.name,
    new Map((tracked.get(example.name) ?? []).map((path) => [comparedPath(example, path), path]))]));
  const input = {
    examples: examples.map((example) => example.name),
    filesOf: (example) => [...realPaths.get(example).keys()],
    contentOf: (example, path) => readFileSync(join(repoRoot, 'examples', example, realPaths.get(example).get(path)), 'utf8'),
    manifest,
  };
  if (process.argv.includes('--update')) {
    writeFileSync(lockFile, lockHeader + stringify(identicalGroups(snapshot(input)), { lineWidth: 0 }));
    console.log('drift.lock.yml updated.');
    return;
  }
  const lock = existsSync(lockFile) ? (parse(readFileSync(lockFile, 'utf8')) ?? []) : [];
  const found = [
    ...checkDrift({ ...input, lock }),
    ...examples.flatMap((example) => variantViolations(
      example,
      variantFilesOf(example, tracked.get(example.name) ?? []),
      (path) => readFileSync(join(repoRoot, 'examples', example.name, path), 'latin1'),
      manifest.languageOnly ?? [],
      engineNormalizer(manifest.engines),
    )),
  ];
  if (found.length > 0) {
    console.error(`The examples drifted apart (${found.length}):\n  ${found.join('\n  ')}`);
    console.error('Bring the copies back in step, or record why they differ in drift.yml; then npm run drift:update.');
    process.exit(1);
  }
  console.log(`${input.examples.length} examples in step: ${lock.reduce((sum, group) => sum + group.files.length * group.examples.length, 0)} locked copies, every other file has a reason.`);
}

if (import.meta.url === `file://${process.argv[1]}`) run();
