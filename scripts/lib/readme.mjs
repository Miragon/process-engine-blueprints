import { variantsOf } from './examples.mjs';

const engines = {
  cibseven: 'CIB seven',
  operaton: 'Operaton',
  fluxnova: 'Fluxnova',
  zeebe: 'Camunda 8 (Zeebe)',
};

const integrations = {
  embedded: 'embedded · JavaDelegates',
  'process-engine-api': 'embedded · process-engine-api',
  remote: 'remote engine host · external tasks',
  native: 'Zeebe cluster · job workers',
  vanillabp: 'Zeebe cluster · VanillaBP',
};

const languageNames = { 'kotlin-gradle': 'Kotlin', 'java-maven': 'Java' };

function markersOf(block) {
  return { begin: `<!-- BEGIN:${block} (generated by npm run generate, do not edit) -->`, end: `<!-- END:${block} -->` };
}

export function examplesTable(examples) {
  const rows = examples.map((example) => {
    const link = `[\`${example.name}\`](examples/${example.name}/README.md)`;
    return `| ${link} | ${engines[example.engine]} | ${example.topology} | ${languagesCell(example)} |`;
  });
  return ['| Example | Engine | Setup | Language |', '| --- | --- | --- | --- |', ...rows].join('\n');
}

function languagesCell(example) {
  const links = variantsOf(example).map(({ variant, path }) => {
    const readme = path === '.' ? 'README.md' : `${path}/README.md`;
    return `[${languageNames[variant]}](examples/${example.name}/${readme})`;
  });
  return links.join(' · ');
}

export function badges(repository) {
  const ci = `https://github.com/${repository}/actions/workflows/ci.yml`;
  return `[![CI](${ci}/badge.svg?branch=main)](${ci}) [![License: MIT](https://img.shields.io/badge/License-MIT-blue.svg)](LICENSE)`;
}

function withBlock(readme, block, content) {
  const { begin, end } = markersOf(block);
  const from = readme.indexOf(begin);
  const to = readme.indexOf(end);
  if (from < 0 || to < from) {
    throw new Error(`README.md lacks the generated ${block} markers`);
  }
  return `${readme.slice(0, from + begin.length)}\n${content}\n${readme.slice(to)}`;
}

export function withGeneratedBlocks(readme, examples, repository) {
  return withBlock(withBlock(readme, 'badges', badges(repository)), 'examples', examplesTable(examples));
}

export { engines, integrations };
