import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { starterCatalog, renderCatalog } from './lib/catalog.mjs';
import { conductorSettings, renderConductor } from './lib/conductor.mjs';
import { dependabotConfig, renderDependabot } from './lib/dependabot.mjs';
import { loadExamples, repoRoot } from './lib/examples.mjs';
import { withExamplesTable } from './lib/readme.mjs';
import { ciWorkflow, exampleWorkflows, nightlyWorkflow, renderWorkflow, reusableWorkflow } from './lib/workflows.mjs';

const generatedMarker = 'Generated by `npm run generate`';
const header = (source) => `# ${generatedMarker} from ${source}. Do not edit: change the source and regenerate.`;
const workflowsDir = join(repoRoot, '.github', 'workflows');

function cliPackageWithRepository() {
  const { repository } = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
  const cliPackage = JSON.parse(readFileSync(join(repoRoot, 'tooling/create-blueprint/package.json'), 'utf8'));
  return `${JSON.stringify({ ...cliPackage, repository: { ...cliPackage.repository, url: repository.url } }, null, 2)}\n`;
}

function releasePleaseConfig(examples) {
  const config = JSON.parse(readFileSync(join(repoRoot, 'release-please-config.json'), 'utf8'));
  const examplePackages = Object.fromEntries(examples.map((example) => [`examples/${example.name}`, { component: example.name }]));
  const otherPackages = Object.fromEntries(Object.entries(config.packages).filter(([path]) => !path.startsWith('examples/')));
  return `${JSON.stringify({ ...config, packages: { ...examplePackages, ...otherPackages } }, null, 2)}\n`;
}

function expectedFiles(examples) {
  const files = new Map();
  for (const example of examples) {
    for (const workflow of exampleWorkflows(example)) {
      const source = `examples/${example.name}/.github/workflows/${workflow.file}`;
      files.set(`.github/workflows/${workflow.generatedFile}`, renderWorkflow(header(source), reusableWorkflow(example, workflow)));
    }
  }
  files.set('.github/workflows/ci.yml', renderWorkflow(header('examples/*/blueprint.yaml'), ciWorkflow(examples)));
  files.set('.github/workflows/nightly.yml', renderWorkflow(header('examples/*/blueprint.yaml'), nightlyWorkflow(examples)));
  files.set('.github/dependabot.yml', renderDependabot(header('examples/*/.github/dependabot.yml'), dependabotConfig(examples)));
  files.set('.conductor/settings.toml', renderConductor(header('examples/*/.conductor/settings.toml'), conductorSettings(examples)));
  files.set('tooling/create-blueprint/catalog.json', renderCatalog(starterCatalog(examples)));
  files.set('tooling/create-blueprint/package.json', cliPackageWithRepository());
  files.set('release-please-config.json', releasePleaseConfig(examples));
  files.set('README.md', withExamplesTable(readFileSync(join(repoRoot, 'README.md'), 'utf8'), examples));
  return files;
}

function staleGeneratedWorkflows(expected) {
  return readdirSync(workflowsDir)
    .map((file) => `.github/workflows/${file}`)
    .filter((file) => !expected.has(file) && readFileSync(join(repoRoot, file), 'utf8').includes(generatedMarker));
}

const actionPin = /^(\s*-?\s*uses:\s*[^@\s]+)@.*$/gm;

function withoutActionPins(content) {
  return content.replace(actionPin, '$1@<pin>');
}

function differences(expected) {
  const changed = [...expected].filter(
    ([file, content]) => !existsSync(join(repoRoot, file)) || withoutActionPins(readFileSync(join(repoRoot, file), 'utf8')) !== withoutActionPins(content),
  );
  return { changed: changed.map(([file]) => file), stale: staleGeneratedWorkflows(expected) };
}

const pinnedInPlace = ['.github/workflows/ci.yml', '.github/workflows/nightly.yml'];

function withPinsOf(existing, content) {
  const pins = new Map([...existing.matchAll(/uses:\s*([^@\s]+)@(.*)$/gm)].map(([, action, pin]) => [action, pin]));
  return content.replace(/(uses:\s*)([^@\s]+)@(.*)$/gm, (line, prefix, action) => (pins.has(action) ? `${prefix}${action}@${pins.get(action)}` : line));
}

function write(expected, { changed, stale }) {
  for (const file of changed) {
    const path = join(repoRoot, file);
    mkdirSync(dirname(path), { recursive: true });
    const keepsItsPins = pinnedInPlace.includes(file) && existsSync(path);
    writeFileSync(path, keepsItsPins ? withPinsOf(readFileSync(path, 'utf8'), expected.get(file)) : expected.get(file));
  }
  for (const file of stale) {
    rmSync(join(repoRoot, file));
  }
}

const expected = expectedFiles(loadExamples());
const { changed, stale } = differences(expected);
const outOfSync = [...changed, ...stale.map((file) => `${file} (no longer generated)`)];

if (process.argv.includes('--check')) {
  if (outOfSync.length > 0) {
    console.error(`Generated files are out of sync, run \`npm run generate\`:\n  ${outOfSync.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`All ${expected.size} generated files are in sync.`);
} else {
  write(expected, { changed, stale });
  console.log(outOfSync.length === 0 ? 'Nothing to regenerate.' : `Regenerated:\n  ${outOfSync.map((file) => relative('.', file)).join('\n  ')}`);
}
