import { variantLabels, variantsOf } from './examples.mjs';

const engines = {
  cibseven: 'CIB seven',
  operaton: 'Operaton',
  fluxnova: 'Fluxnova',
  zeebe: 'Camunda 8 (Zeebe)',
};

const integrations = {
  embedded: 'Embedded engine, JavaDelegates',
  'process-engine-api': 'Embedded engine, bpm-crafters process-engine-api',
  remote: 'Remote engine host, external tasks',
  native: 'Zeebe broker, Spring job workers',
  vanillabp: 'Zeebe broker, VanillaBP',
};

export const markers = {
  begin: '<!-- BEGIN:examples (generated by npm run generate, do not edit) -->',
  end: '<!-- END:examples -->',
};

export function examplesTable(examples) {
  const rows = examples.map((example) => {
    const link = `[\`${example.name}\`](examples/${example.name}/README.md)`;
    const variants = Object.keys(variantLabels)
      .map((variant) => variantCell(example, variant))
      .join(' | ');
    return `| ${link} | ${engines[example.engine]} | ${integrations[example.integration]} | ${example.topology} | ${variants} | ${example.stack} |`;
  });
  return [
    '| Example | Engine | Integration | Topology | Kotlin · Gradle | Java · Maven | Local stack |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

function variantCell(example, variant) {
  const present = variantsOf(example).find((candidate) => candidate.variant === variant);
  if (!present) {
    return `— (${example.missingVariants[variant] ?? 'not available'})`;
  }
  const readme = present.path === '.' ? 'README.md' : `${present.path}/README.md`;
  return `[${variant}](examples/${example.name}/${readme})`;
}

export function withExamplesTable(readme, examples) {
  const begin = readme.indexOf(markers.begin);
  const end = readme.indexOf(markers.end);
  if (begin < 0 || end < begin) {
    throw new Error('README.md lacks the generated examples markers');
  }
  return `${readme.slice(0, begin + markers.begin.length)}\n${examplesTable(examples)}\n${readme.slice(end)}`;
}

export { engines, integrations };
