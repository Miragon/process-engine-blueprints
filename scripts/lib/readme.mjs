import { variantsOf } from './examples.mjs';

const engines = {
  cibseven: 'CIB seven',
  operaton: 'Operaton',
  fluxnova: 'Fluxnova',
  zeebe: 'Camunda 8 (Zeebe)',
};

const integrations = {
  embedded: 'embedded · JavaDelegates',
  'process-engine-api': 'embedded · process-engine-api',
  remote: 'remote engine host · external tasks',
  native: 'Zeebe cluster · job workers',
  vanillabp: 'Zeebe cluster · VanillaBP',
};

const languageNames = { 'kotlin-gradle': 'Kotlin', 'java-maven': 'Java' };

export const markers = {
  begin: '<!-- BEGIN:examples (generated by npm run generate, do not edit) -->',
  end: '<!-- END:examples -->',
};

export function examplesTable(examples) {
  const rows = examples.map((example) => {
    const link = `[\`${example.name}\`](examples/${example.name}/README.md)`;
    const withUi = example.frontend ? ' · React UI' : '';
    return `| ${link} | ${engines[example.engine]} | ${integrations[example.integration]}${withUi} | ${languagesCell(example)} |`;
  });
  return ['| Example | Engine | Setup | Language |', '| --- | --- | --- | --- |', ...rows].join('\n');
}

function languagesCell(example) {
  const links = variantsOf(example).map(({ variant, path }) => {
    const readme = path === '.' ? 'README.md' : `${path}/README.md`;
    return `[${languageNames[variant]}](examples/${example.name}/${readme})`;
  });
  return links.length === 1 ? `${links[0]} only` : links.join(' · ');
}

export function withExamplesTable(readme, examples) {
  const begin = readme.indexOf(markers.begin);
  const end = readme.indexOf(markers.end);
  if (begin < 0 || end < begin) {
    throw new Error('README.md lacks the generated examples markers');
  }
  return `${readme.slice(0, begin + markers.begin.length)}\n${examplesTable(examples)}\n${readme.slice(end)}`;
}

export { engines, integrations };
